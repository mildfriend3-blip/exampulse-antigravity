/**
 * Export & Offline Capability Screen
 * Printable clean university-standard view for offline practice and peer sharing.
 */
@Composable
fun PrintableViewScreen(viewModel: AntigravityViewModel) {
    val uiState by viewModel.uiState.collectAsState()
    val paper = uiState.currentPaper
    val context = LocalContext.current

    val formattedPaperText = remember(paper) {
        buildString {
            appendLine("=".repeat(60))
            appendLine(paper.university.uppercase())
            appendLine(paper.degree)
            appendLine("Subject: [${paper.subjectCode}] ${paper.subjectTitle}")
            appendLine("Duration: ${paper.durationMinutes / 60} Hours | Maximum Marks: ${paper.maximumMarks}")
            appendLine("=".repeat(60))
            appendLine()
            appendLine("INSTRUCTIONS TO CANDIDATES:")
            appendLine("1. Section A is COMPULSORY. Answer all questions (2 marks each).")
            appendLine("2. Section B: Attempt any FOUR questions (5 marks each).")
            appendLine("3. Section C: Attempt THREE questions with internal choice (10 marks each).")
            appendLine("-".repeat(60))
            appendLine()
            appendLine("SECTION A (Compulsory - 20 Marks)")
            paper.sectionA.forEach { q ->
                appendLine("${q.number} ${q.text}  [${q.marks}M]")
            }
            appendLine()
            appendLine("SECTION B (Attempt Any 4 - 20 Marks)")
            paper.sectionB.forEach { q ->
                appendLine("${q.number} ${q.text}  [${q.marks}M]")
            }
            appendLine()
            appendLine("SECTION C (Attempt 3 with Internal Choice - 30 Marks)")
            paper.sectionC.forEach { q ->
                appendLine("${q.number} ${q.text}  [${q.marks}M]")
                if (q.hasInternalChoice && q.alternativeQuestion != null) {
                    appendLine("    ${q.alternativeQuestion}")
                }
            }
            appendLine()
            appendLine("=".repeat(60))
            appendLine("Generated by Antigravity ExamPulse Engine for University Engineering Students")
        }
    }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .padding(16.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {
        // Top Action Bar
        GlassmorphicCard(borderColor = CyberCyan.copy(alpha = 0.5f)) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Column {
                    Text(
                        text = "OFFICIAL UNIVERSITY PRINT VIEW",
                        color = CyberCyan,
                        fontSize = 12.sp,
                        fontWeight = FontWeight.Bold,
                        fontFamily = FontFamily.Monospace
                    )
                    Text(
                        text = "Clean standard exam format for print & offline study",
                        color = TextMuted,
                        fontSize = 11.sp
                    )
                }

                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    Button(
                        onClick = {
                            val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
                            val clip = ClipData.newPlainText("Exam Paper", formattedPaperText)
                            clipboard.setPrimaryClip(clip)
                            Toast.makeText(context, "Copied formatted paper to clipboard!", Toast.LENGTH_SHORT).show()
                        },
                        colors = ButtonDefaults.buttonColors(containerColor = CyberCyan),
                        shape = RoundedCornerShape(8.dp)
                    ) {
                        Icon(Icons.Default.ContentCopy, contentDescription = null, tint = CosmicDeep, modifier = Modifier.size(16.dp))
                        Spacer(modifier = Modifier.width(6.dp))
                        Text("COPY PAPER", color = CosmicDeep, fontWeight = FontWeight.Bold, fontFamily = FontFamily.Monospace, fontSize = 11.sp)
                    }
                }
            }
        }

        // Clean Printable Paper Document View
        Surface(
            modifier = Modifier
                .fillMaxWidth()
                .weight(1f)
                .border(1.dp, CyberBorderStroke, RoundedCornerShape(12.dp)),
            color = CosmicSurface.copy(alpha = 0.9f),
            shape = RoundedCornerShape(12.dp)
        ) {
            Column(
                modifier = Modifier
                    .fillMaxSize()
                    .padding(16.dp)
                    .verticalScroll(rememberScrollState())
            ) {
                Text(
                    text = formattedPaperText,
                    color = TextHighContrast,
                    fontFamily = FontFamily.Monospace,
                    fontSize = 12.sp,
                    lineHeight = 18.sp
                )
            }
        }
    }
}
